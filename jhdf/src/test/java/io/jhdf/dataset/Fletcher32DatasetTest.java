package io.jhdf.dataset;

import io.jhdf.HdfFile;
import io.jhdf.api.Dataset;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DynamicNode;
import org.junit.jupiter.api.TestFactory;

import java.util.Arrays;
import java.util.Collection;
import java.util.function.BiFunction;

import static io.jhdf.TestUtils.loadTestHdfFile;
import static io.jhdf.Utils.flatten;
import static io.jhdf.Utils.getDimensions;
import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.DynamicContainer.dynamicContainer;
import static org.junit.jupiter.api.DynamicTest.dynamicTest;

/**
 * Reads datasets written with the 'fletcher32' checksum filter.
 * <p>
 * The test files are generated by h5py (which uses the HDF5 C library) with
 * {@code fletcher32=True}, see {@code src/test/resources/scripts/fletcher_datasets.py}.
 * The dataset data is {@code np.arange(35).reshape(7, 5)}, so successfully reading
 * the datasets validates the Fletcher32 checksum verification against an
 * independent third-party implementation.
 */
class Fletcher32DatasetTest {

	private static final String EARLIEST_FILE = "fletcher32_datasets_earliest.hdf5";
	private static final String LATEST_FILE = "fletcher32_datasets_latest.hdf5";

	private static HdfFile earliestHdfFile;
	private static HdfFile latestHdfFile;

	@BeforeAll
	static void setup() {
		earliestHdfFile = loadTestHdfFile(EARLIEST_FILE);
		latestHdfFile = loadTestHdfFile(LATEST_FILE);
	}

	@AfterAll
	static void tearDown() {
		earliestHdfFile.close();
		latestHdfFile.close();
	}

	@TestFactory
	Collection<DynamicNode> fletcher32DatasetsReadCorrectly() {
		// Path -> expected data
		BiFunction<String, HdfFile, DynamicNode> test = (path, file) ->
			dynamicTest(path, () -> assertFletcher32Dataset(file, path));

		return Arrays.asList(
			dynamicContainer(EARLIEST_FILE, Arrays.asList(
				test.apply("/float/float32", earliestHdfFile),
				test.apply("/float/float64", earliestHdfFile),
				test.apply("/int/int8", earliestHdfFile),
				test.apply("/int/int16", earliestHdfFile),
				test.apply("/int/int32", earliestHdfFile))),
			dynamicContainer(LATEST_FILE, Arrays.asList(
				test.apply("/float/float32", latestHdfFile),
				test.apply("/float/float64", latestHdfFile),
				test.apply("/int/int8", latestHdfFile),
				test.apply("/int/int16", latestHdfFile),
				test.apply("/int/int32", latestHdfFile))));
	}

	private static void assertFletcher32Dataset(HdfFile hdfFile, String path) {
		Dataset dataset = hdfFile.getDatasetByPath(path);
		Object data = dataset.getData();

		// The dataset data is np.arange(35).reshape(7, 5)
		assertThat(getDimensions(data)).isEqualTo(new int[]{7, 5});

		Object[] flatData = flatten(data);
		assertThat(flatData).hasSize(35);
		for (int i = 0; i < flatData.length; i++) {
			// Do element comparison as the datasets have all different primitive
			// numeric types, so convert to double
			assertThat(((Number) flatData[i]).doubleValue()).isEqualTo((double) i);
		}
	}
}
