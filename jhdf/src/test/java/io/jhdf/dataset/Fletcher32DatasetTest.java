package io.jhdf.dataset;

import io.jhdf.HdfFile;
import io.jhdf.api.Dataset;
import io.jhdf.api.dataset.ChunkedDataset;
import io.jhdf.checksum.Fletcher32;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DynamicNode;
import org.junit.jupiter.api.TestFactory;

import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.util.Arrays;
import java.util.Collection;
import java.util.function.BiFunction;

import static io.jhdf.TestUtils.loadTestHdfFile;
import static io.jhdf.Utils.flatten;
import static io.jhdf.Utils.getDimensions;
import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.DynamicContainer.dynamicContainer;
import static org.junit.jupiter.api.DynamicTest.dynamicTest;

/**
 * Reads datasets written with the 'fletcher32' checksum filter.
 * <p>
 * The test files are generated by h5py (which uses the HDF5 C library) with
 * {@code fletcher32=True}, see {@code src/test/resources/scripts/fletcher_datasets.py}.
 * The dataset data is {@code np.arange(35).reshape(7, 5)}. The checksums stored in
 * the files are validated by recomputing them with {@link Fletcher32}, so the tests
 * validate the checksum verification against an independent third-party
 * implementation.
 */
class Fletcher32DatasetTest {

	private static final String EARLIEST_FILE = "fletcher32_datasets_earliest.hdf5";
	private static final String LATEST_FILE = "fletcher32_datasets_latest.hdf5";

	private static final String[] DATASET_PATHS = {
		"/float/float32", "/float/float64", "/int/int8", "/int/int16", "/int/int32"
	};

	/** Number of bytes in the fletcher32 checksum */
	private static final int CHECKSUM_LENGTH = 4;

	private static HdfFile earliestHdfFile;
	private static HdfFile latestHdfFile;

	@BeforeAll
	static void setup() {
		earliestHdfFile = loadTestHdfFile(EARLIEST_FILE);
		latestHdfFile = loadTestHdfFile(LATEST_FILE);
	}

	@AfterAll
	static void tearDown() {
		earliestHdfFile.close();
		latestHdfFile.close();
	}

	@TestFactory
	Collection<DynamicNode> fletcher32DatasetsReadCorrectly() {
		return createFileContainers((file, path) -> dynamicTest(path, () -> assertFletcher32Dataset(file, path)));
	}

	@TestFactory
	Collection<DynamicNode> fletcher32ChunkChecksumsAreValid() {
		return createFileContainers((file, path) -> dynamicTest(path, () -> assertChunkChecksumsAreValid(file, path)));
	}

	private static Collection<DynamicNode> createFileContainers(BiFunction<HdfFile, String, DynamicNode> test) {
		return Arrays.asList(
			dynamicContainer(EARLIEST_FILE,
				Arrays.stream(DATASET_PATHS).map(path -> test.apply(earliestHdfFile, path))),
			dynamicContainer(LATEST_FILE,
				Arrays.stream(DATASET_PATHS).map(path -> test.apply(latestHdfFile, path))));
	}

	private static void assertFletcher32Dataset(HdfFile hdfFile, String path) {
		Dataset dataset = hdfFile.getDatasetByPath(path);
		Object data = dataset.getData();

		// The dataset data is np.arange(35).reshape(7, 5)
		assertThat(getDimensions(data)).isEqualTo(new int[]{7, 5});

		Object[] flatData = flatten(data);
		assertThat(flatData).hasSize(35);
		for (int i = 0; i < flatData.length; i++) {
			// Do element comparison as the datasets have all different primitive
			// numeric types, so convert to double
			assertThat(((Number) flatData[i]).doubleValue()).isEqualTo((double) i);
		}
	}

	/**
	 * Independently validates the checksum of every chunk in the dataset. The raw
	 * chunk is the chunk data with the 4 byte little-endian fletcher32 checksum
	 * appended, so the checksum of all but the last 4 bytes must equal the stored
	 * checksum.
	 */
	private static void assertChunkChecksumsAreValid(HdfFile hdfFile, String path) {
		Dataset dataset = hdfFile.getDatasetByPath(path);
		assertThat(dataset).isInstanceOf(ChunkedDataset.class);
		ChunkedDataset chunkedDataset = (ChunkedDataset) dataset;

		int[] dimensions = chunkedDataset.getDimensions();
		int[] chunkDimensions = chunkedDataset.getChunkDimensions();

		// Number of chunks along each dimension
		int[] chunkCounts = new int[dimensions.length];
		int totalChunks = 1;
		for (int i = 0; i < dimensions.length; i++) {
			chunkCounts[i] = (int) Math.ceil((double) dimensions[i] / chunkDimensions[i]);
			totalChunks *= chunkCounts[i];
		}

		for (int chunkIndex = 0; chunkIndex < totalChunks; chunkIndex++) {
			int[] chunkOffset = decodeChunkOffset(chunkIndex, chunkCounts, chunkDimensions);
			byte[] rawChunk = readRawChunk(chunkedDataset, chunkOffset);

			// The last 4 bytes are the little-endian checksum of the rest of the chunk
			int dataLength = rawChunk.length - CHECKSUM_LENGTH;
			int storedChecksum = ByteBuffer.wrap(rawChunk, dataLength, CHECKSUM_LENGTH)
				.order(ByteOrder.LITTLE_ENDIAN)
				.getInt();

			assertThat(Fletcher32.checksum(rawChunk, 0, dataLength))
				.as("checksum of chunk %s of %s", Arrays.toString(chunkOffset), path)
				.isEqualTo(storedChecksum);
		}
	}

	/**
	 * Decodes a flat chunk index into a chunk offset. The chunk offset is the
	 * offset of the chunk's first element, i.e. the chunk index multiplied by the
	 * chunk dimensions.
	 */
	private static int[] decodeChunkOffset(int chunkIndex, int[] chunkCounts, int[] chunkDimensions) {
		int[] chunkOffset = new int[chunkCounts.length];
		int remaining = chunkIndex;
		for (int i = chunkCounts.length - 1; i >= 0; i--) {
			int index = remaining % chunkCounts[i];
			remaining /= chunkCounts[i];
			chunkOffset[i] = index * chunkDimensions[i];
		}
		return chunkOffset;
	}

	private static byte[] readRawChunk(ChunkedDataset chunkedDataset, int[] chunkOffset) {
		ByteBuffer rawChunkBuffer = chunkedDataset.getRawChunkBuffer(chunkOffset);
		byte[] rawChunk = new byte[rawChunkBuffer.remaining()];
		rawChunkBuffer.get(rawChunk);
		return rawChunk;
	}
}
